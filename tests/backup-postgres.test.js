import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { randomUUID, createHash } from 'node:crypto';
import { isolatedPostgres } from './helpers/isolated-postgres.mjs';
import { createInventoryRepository } from '../server/inventory.js';
import { backupDatabase } from '../tools/backup-database.mjs';
import { startTestServer, testClient } from './helpers/auth-server.mjs';

test('custom dump restores balances, history, receipts and relationships into a separate disposable database', { skip: !process.env.TEST_PG_BIN }, async t => {
  const db = await isolatedPostgres(); let restoredPool, server;
  t.after(async () => { if (server) await server.close(); if (restoredPool) await restoredPool.end(); await db.close(); });
  const directory = await mkdtemp(resolve('tests/artifacts/backup-'));
  t.after(async () => { if (!directory.startsWith(resolve('tests/artifacts') + (process.platform === 'win32' ? '\\' : '/'))) throw Error('Unsafe cleanup'); await rm(directory, { recursive: true, force: true }); });
  const repo = createInventoryRepository(db.pool);
  await db.owner.query(await readFile(new URL('../db/migrations/004-material-archive.sql', import.meta.url), 'utf8'));
  await db.owner.query("INSERT INTO public.admin_account(id,username,password_hash) VALUES(1,'synthetic','protected-test-hash')");
  await db.owner.query("INSERT INTO public.inventory_sessions VALUES('test-session','{}',CURRENT_TIMESTAMP + interval '1 hour')");
  const category = await repo.create('categories', { name: 'کیبل' }, randomUUID());
  const supplier = await repo.create('suppliers', { name: 'Test supplier' }, randomUUID());
  const key = randomUUID(), body = { name: 'Cable', categoryId: category.id, supplierId: supplier.id, price: '0.01' };
  const material = await repo.create('materials', body, key);
  const operation = { operationId: randomUUID(), type: 'add', items: [{ materialId: material.id, quantity: '2.125' }] };
  await repo.operateStock(operation, 1);
  await repo.operateStock({ operationId: randomUUID(), type: 'remove', items: [{ materialId: material.id, quantity: '0.500' }] }, 1);
  const connection = db.owner.options;
  // This generated credential belongs only to isolatedPostgres(), never .env.
  const env = { ...process.env, PGPASSWORD: connection.password };
  const backup = await backupDatabase({ bin: process.env.TEST_PG_BIN, directory, database: connection.database, username: connection.user, host: connection.host, port: connection.port, env });
  assert.equal(createHash('sha256').update(await readFile(backup.file)).digest('hex'), backup.sha256);
  await db.owner.query('CREATE DATABASE inventory_restore_test');
  const run = promisify(execFile), executable = join(process.env.TEST_PG_BIN, 'pg_restore' + (process.platform === 'win32' ? '.exe' : ''));
  await run(executable, ['--host', connection.host, '--port', String(connection.port), '--username', connection.user, '--dbname', 'inventory_restore_test', '--no-password', '--no-owner', '--exit-on-error', '--single-transaction', backup.file], { env, windowsHide: true });
  restoredPool = new pg.Pool({ host: connection.host, port: connection.port, user: connection.user, password: connection.password, database: 'inventory_restore_test' });
  const restored = createInventoryRepository(restoredPool);
  const withoutVersion = rows => rows.map(({ version, ...row }) => row);
  assert.deepEqual(withoutVersion(await restored.listMaterials()), withoutVersion(await repo.listMaterials()));
  assert.deepEqual(withoutVersion(await restored.listCategories()), withoutVersion(await repo.listCategories()));
  assert.deepEqual(withoutVersion(await restored.listSuppliers()), withoutVersion(await repo.listSuppliers()));
  assert.deepEqual(await restored.listMovements({}), await repo.listMovements({}));
  assert.equal((await restored.findMaterial(material.id)).quantity, '1.625');
  assert.equal((await restored.create('materials', body, key)).id, material.id);
  assert.equal((await restored.operateStock(operation, 1)).replayed, true);
  assert.equal((await restored.findMaterial(material.id)).quantity, '1.625');
  assert.equal((await restoredPool.query('SELECT count(*) FROM public.inventory_sessions')).rows[0].count, '0');
  assert.equal((await restoredPool.query('SELECT count(*) FROM public.inventory_create_requests')).rows[0].count, '3');
  assert.equal((await restoredPool.query('SELECT password_hash FROM public.admin_account')).rows[0].password_hash, 'protected-test-hash');
  assert.equal((await restoredPool.query('SELECT count(*) FROM public.stock_movements sm LEFT JOIN public.materials m ON m.id=sm.material_id WHERE m.id IS NULL')).rows[0].count, '0');
  await assert.rejects(restoredPool.query('DELETE FROM public.categories WHERE id=$1', [category.id]), error => ['23001','23503'].includes(error.code));
  server = await startTestServer({ inventory: restored }); const client = testClient(server.url); await client.login();
  const response = await client.request('/api/materials'); assert.equal(response.status, 200); assert.equal((await response.json()).data[0].quantity, '1.625');
});
